; =====================================================================================
;  Минимальный монитор «Специалиста», шаг 1: проснуться и показать, что жив.
;  Сборка: python3 ../shell/tools/asm80.py step1.asm -o step1.rom --base C000 --size 800
; =====================================================================================

SCREEN  EQU 9000h           ; начало экранной памяти
PPI_CTL EQU 0FF03h          ; регистр управления ВВ55 (клавиатура, магнитофон)

        ORG 0C000h

; После сброса процессор начинает с адреса 0000. Схема «Специалиста» в этот момент
; показывает ПЗУ и по адресу 0000, поэтому первой командой стоит переход на настоящий
; адрес в ПЗУ — как у штатного монитора (C000: JMP C003).
RESET:  JMP START

START:  LXI SP,8000h        ; стек: растёт вниз от 7FFF
        MVI A,82h           ; ВВ55: порты A и C — выход, B — вход (клавиатура)
        STA PPI_CTL

        ; очистить экран: 3000h байт нулями
        LXI H,SCREEN
        LXI B,3000h
CLR:    MVI M,0
        INX H
        DCX B
        MOV A,B
        ORA C
        JNZ CLR

        ; признак жизни: рамка по краю экрана
        LXI H,SCREEN        ; левый столбец: самая левая точка в каждой строке
        MVI B,0             ; 256 строк
LEFT:   MVI M,80h
        INX H
        DCR B
        JNZ LEFT
        LXI H,SCREEN+2F00h  ; правый столбец (47): самая правая точка
        MVI B,0
RIGHT:  MVI M,01h
        INX H
        DCR B
        JNZ RIGHT
        LXI H,SCREEN        ; верх и низ: строки 0 и 255 в каждом из 48 столбцов
        MVI B,48
TOPBOT: MVI M,0FFh          ; строка 0
        MVI L,0FFh
        MVI M,0FFh          ; строка 255
        MVI L,0
        INR H               ; следующий столбец
        DCR B
        JNZ TOPBOT

STOP:   JMP STOP            ; дальше пока делать нечего
