; =====================================================================================
;  Минимальный монитор, шаг 2: свой шрифт (только 0-9, A-F и три знака) и вывод на экран.
;  Клетка символа 8×8 точек = ровно один байт в ширину: на экране 48 столбцов × 32 строки.
;  Символ рисуется так: 8 байт его картинки кладутся в 8 соседних байтов экрана (одна
;  клетка = 8 строк одного столбца экрана).
; =====================================================================================

SCREEN  EQU 9000h
PPI_CTL EQU 0FF03h

; переменные — в ОЗУ под стеком
CURX    EQU 7F00h           ; столбец курсора 0..47
CURY    EQU 7F01h           ; строка курсора 0..31

; номера символов в нашем шрифте
CH_SP   EQU 16              ; пробел
CH_COL  EQU 17              ; двоеточие
CH_GT   EQU 18              ; >

        ORG 0C000h
RESET:  JMP START

START:  LXI SP,7F00h        ; стек под переменными: растёт вниз от 7EFF
        MVI A,82h
        STA PPI_CTL
        CALL CLS

        ; строка 1: все символы шрифта
        MVI B,0
ALL:    MOV A,B
        CALL PUTCH
        INR B
        MOV A,B
        CPI 19
        JNZ ALL
        CALL NEWLINE

        ; строка 2: «C000: C3 03 C0 31 FF 7F 3E 82» — начало нашего же ПЗУ
        CALL NEWLINE
        LXI H,0C000h
        CALL PHEX16
        MVI A,CH_COL
        CALL PUTCH
        MVI B,8
DUMP:   MVI A,CH_SP
        CALL PUTCH
        MOV A,M
        CALL PHEX8
        INX H
        DCR B
        JNZ DUMP
        CALL NEWLINE
        MVI A,CH_GT
        CALL PUTCH

STOP:   JMP STOP

; ---------------------------------------------------------------- подпрограммы
; очистить экран, курсор в левый верхний угол
CLS:    LXI H,SCREEN
        LXI B,3000h
.l:     MVI M,0
        INX H
        DCX B
        MOV A,B
        ORA C
        JNZ .l
        XRA A
        STA CURX
        STA CURY
        RET

; новая строка
NEWLINE:
        XRA A
        STA CURX
        LDA CURY
        INR A
        STA CURY
        RET

; нарисовать символ номер A в позиции курсора, курсор вправо. Регистры сохраняются.
PUTCH:  PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        ; DE = адрес картинки символа = FONT + номер * 8
        MOV L,A
        MVI H,0
        DAD H               ; * 2
        DAD H               ; * 4
        DAD H               ; * 8
        LXI D,FONT
        DAD D
        XCHG
        ; HL = адрес на экране = 9000 + столбец * 100h + строка * 8
        LDA CURX
        ADI 90h
        MOV H,A             ; старший байт адреса = 90 + столбец
        LDA CURY
        ADD A               ; * 2
        ADD A               ; * 4
        ADD A               ; * 8
        MOV L,A             ; младший байт = строка * 8
        ; 8 байт картинки -> 8 строк экрана подряд
        MVI B,8
.c:     LDAX D
        MOV M,A
        INX D
        INX H
        DCR B
        JNZ .c
        ; курсор вправо
        LDA CURX
        INR A
        STA CURX
        POP H
        POP D
        POP B
        POP PSW
        RET

; A двумя hex-цифрами
PHEX8:  PUSH PSW
        RRC                 ; старшая половина байта -> младшая
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL PUTCH          ; номер цифры = её значение: 0-9, A-F = 10-15
        POP PSW
        ANI 0Fh
        JMP PUTCH

; HL четырьмя hex-цифрами
PHEX16: MOV A,H
        CALL PHEX8
        MOV A,L
        JMP PHEX8

; ---------------------------------------------------------------- шрифт
; 8 байт на символ, сверху вниз; бит 7 — левая точка. Номер символа = его место здесь.
FONT:   DB 00111100b,01000110b,01001010b,01010010b,01100010b,01000010b,00111100b,0 ; 0
        DB 00001000b,00011000b,00101000b,00001000b,00001000b,00001000b,00111110b,0 ; 1
        DB 00111100b,01000010b,00000010b,00001100b,00110000b,01000000b,01111110b,0 ; 2
        DB 00111100b,01000010b,00000010b,00011100b,00000010b,01000010b,00111100b,0 ; 3
        DB 00000100b,00001100b,00010100b,00100100b,01111110b,00000100b,00000100b,0 ; 4
        DB 01111110b,01000000b,01111100b,00000010b,00000010b,01000010b,00111100b,0 ; 5
        DB 00011100b,00100000b,01000000b,01111100b,01000010b,01000010b,00111100b,0 ; 6
        DB 01111110b,00000010b,00000100b,00001000b,00010000b,00010000b,00010000b,0 ; 7
        DB 00111100b,01000010b,01000010b,00111100b,01000010b,01000010b,00111100b,0 ; 8
        DB 00111100b,01000010b,01000010b,00111110b,00000010b,00000100b,00111000b,0 ; 9
        DB 00011000b,00100100b,01000010b,01000010b,01111110b,01000010b,01000010b,0 ; A
        DB 01111100b,01000010b,01000010b,01111100b,01000010b,01000010b,01111100b,0 ; B
        DB 00111100b,01000010b,01000000b,01000000b,01000000b,01000010b,00111100b,0 ; C
        DB 01111000b,01000100b,01000010b,01000010b,01000010b,01000100b,01111000b,0 ; D
        DB 01111110b,01000000b,01000000b,01111100b,01000000b,01000000b,01111110b,0 ; E
        DB 01111110b,01000000b,01000000b,01111100b,01000000b,01000000b,01000000b,0 ; F
        DB 0,0,0,0,0,0,0,0                                                     ; пробел
        DB 0,00011000b,00011000b,0,0,00011000b,00011000b,0                     ; :
        DB 00100000b,00010000b,00001000b,00000100b,00001000b,00010000b,00100000b,0 ; >
