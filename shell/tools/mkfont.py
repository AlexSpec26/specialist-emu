#!/usr/bin/env python3
"""Generates glyphs.inc: shell glyphs for codes 80h-FFh (6 bits per row, bit 5 = left)."""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from lower import L
from asm80 import RU_LOWER, BOX

def box(up, down, left, right, dbl=False):
    g = [[0] * 6 for _ in range(8)]
    hy = [3] if not dbl else [2, 4]
    vx = [2] if not dbl else [1, 3]
    for y in hy:
        if left:
            for x in range(0, max(vx) + 1): g[y][x] = 1
        if right:
            for x in range(min(vx), 6): g[y][x] = 1
    for x in vx:
        if up:
            for y in range(0, max(hy) + 1): g[y][x] = 1
        if down:
            for y in range(min(hy), 8): g[y][x] = 1
    return g

def rows5(ch):
    return [[0] + [1 if c == '#' else 0 for c in r] for r in L[ch]]

def mix_dv(left, right):
    # double vertical with single horizontal: ╟ ╢
    g = box(1, 1, 0, 0, True)
    for x in (range(3, 6) if right else range(0, 2)):
        g[3][x] = 1
    return g

G = {}
for i, ch in enumerate(RU_LOWER):
    G[0x80 + i] = rows5(ch)
for i in range(26):
    G[0xA1 + i] = rows5(chr(ord('a') + i))
B = {
    '─': box(0, 0, 1, 1), '│': box(1, 1, 0, 0), '┌': box(0, 1, 0, 1), '┐': box(0, 1, 1, 0),
    '└': box(1, 0, 0, 1), '┘': box(1, 0, 1, 0), '├': box(1, 1, 0, 1), '┤': box(1, 1, 1, 0),
    '┬': box(0, 1, 1, 1), '┴': box(1, 0, 1, 1), '┼': box(1, 1, 1, 1),
    '═': box(0, 0, 1, 1, True), '║': box(1, 1, 0, 0, True), '╔': box(0, 1, 0, 1, True),
    '╗': box(0, 1, 1, 0, True), '╚': box(1, 0, 0, 1, True), '╝': box(1, 0, 1, 0, True),
    '╟': mix_dv(0, 1), '╢': mix_dv(1, 0),
    '█': [[1] * 6 for _ in range(8)],
    '▒': [[(x + y) % 2 for x in range(6)] for y in range(8)],
    '░': [[1 if (x % 2 == 0 and y % 2 == 0) else 0 for x in range(6)] for y in range(8)],
    '▀': [[1] * 6 if y < 4 else [0] * 6 for y in range(8)],
    '▄': [[0] * 6 if y < 4 else [1] * 6 for y in range(8)],
    '▌': [[1, 1, 1, 0, 0, 0] for _ in range(8)],
    '▐': [[0, 0, 0, 1, 1, 1] for _ in range(8)],
    '·': [[0, 0, 1, 0, 0, 0] if y == 3 else [0] * 6 for y in range(8)],
    '►': [[0, 1 if y in (0, 6) or 1 <= y <= 5 else 0, 1 if 1 <= y <= 5 else 0, 1 if 2 <= y <= 4 else 0, 1 if y == 3 else 0, 0] for y in range(8)],
    '◄': [[0, 0, 0, 0, 0, 0] for _ in range(8)],
    '▲': [[0] * 6 for _ in range(8)],
    '▼': [[0] * 6 for _ in range(8)],
    '✓': [[0] * 6 for _ in range(8)],
}
def art(rows):
    return [[1 if c == '#' else 0 for c in r.ljust(6)] for r in rows]
B['►'] = art(["#     ", "##    ", "###   ", "####  ", "###   ", "##    ", "#     ", "      "])
B['◄'] = art(["   #  ", "  ##  ", " ###  ", "####  ", " ###  ", "  ##  ", "   #  ", "      "])
B['▲'] = art(["      ", "  #   ", " ###  ", "##### ", "      ", "      ", "      ", "      "])
B['▼'] = art(["      ", "##### ", " ###  ", "  #   ", "      ", "      ", "      ", "      "])
B['✓'] = art(["      ", "    # ", "   #  ", "#  #  ", " ##   ", " #    ", "      ", "      "])
for i, ch in enumerate(BOX):
    G[0xE0 + i] = B[ch]
G[0xBB] = rows5('ъ')
G[0xBC] = [[0] + [1 if c == '#' else 0 for c in r] for r in
           ["##...", ".#...", ".#...", ".###.", ".#..#", ".#..#", ".###.", "....."]]

out = ["; generated by mkfont.py: glyphs 80h-FFh, 8 bytes each, bit 5 = leftmost pixel"]
for code in range(0x80, 0x100):
    g = G.get(code, [[0] * 6 for _ in range(8)])
    vals = [sum(row[k] << (5 - k) for k in range(6)) for row in g]
    out.append(f"        DB {', '.join(f'0{v:02X}h' for v in vals)}   ; {code:02X}")
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
