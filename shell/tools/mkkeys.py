#!/usr/bin/env python3
"""Generates keytab.inc: Specialist key matrix (code = column*6 + row) -> shell key codes.
Four tables of 72 bytes: Latin, Latin+НР, Russian, Russian+НР."""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from asm80 import CHARMAP

LABEL = [["ВК", "ЗБ", ".", ":", "-", "СТР"], ["ПС", "/", "\\", "H", "0", "F11"], ["→", ",", "V", "Z", "9", "F10"],
         ["ПВ", "@", "D", "]", "8", "F9"], ["←", "B", "L", "[", "7", "F8"], ["Пробел", "X", "O", "G", "6", "F7"],
         ["АР2", "T", "R", "N", "5", "F6"], ["ТАБ", "I", "P", "E", "4", "F5"], ["↓", "M", "A", "K", "3", "F4"],
         ["↑", "S", "W", "U", "2", "F3"], ["↖", "^", "Y", "C", "1", "F2"], ["Р/Л", "Q", "F", "J", ";", "F1"]]
LABEL2 = [["", "", ">", "*", "=", ""], ["", "?", "Э", "Х", "", ""], ["", "<", "Ж", "З", ")", ""],
          ["", "Ю", "Д", "Щ", "(", ""], ["", "Б", "Л", "Ш", "'", ""], ["", "Ь", "О", "Г", "&", ""],
          ["", "Т", "Р", "Н", "%", ""], ["", "И", "П", "Е", "$", ""], ["", "М", "А", "К", "#", ""],
          ["", "С", "В", "У", "\"", ""], ["", "Ч", "Ы", "Ц", "!", ""], ["", "Я", "Ф", "Й", "+", ""]]
SPECIAL = {"ВК": 0x0D, "ЗБ": 0x1E, "СТР": 0x1F, "ПС": 0x0A, "→": 0x18, "ПВ": 0x00, "←": 0x08, "Пробел": 0x20,
           "АР2": 0x1B, "ТАБ": 0x09, "↓": 0x1A, "↑": 0x19, "↖": 0x0C, "Р/Л": 0xFE}
RU = "АБЦДЕФГХИЙКЛМНОПЯРСТУЖВЬЫЗШЭЩЧЮ"

def code(ch):
    return CHARMAP.get(ch, ord(ch))

tabs = [[0] * 72 for _ in range(4)]
for col in range(12):
    for row in range(6):
        k = col * 6 + row
        l1, l2 = LABEL[col][row], LABEL2[col][row]
        if l1 in SPECIAL:
            v = SPECIAL[l1]
            vals = [v, v, v, v]
        elif l1.startswith("F") and len(l1) > 1:
            n = int(l1[1:])
            vals = [0xC0 + n, 0xD0 + n, 0xC0 + n, 0xD0 + n]
        elif l1.isalpha() and len(l1) == 1:
            lat = l1
            ru = l2 if l2 and l2 in RU else None
            vals = [code(lat.lower()), code(lat), code(ru.lower()) if ru else code(lat.lower()), code(ru) if ru else code(lat)]
        else:
            # digits and symbols; in Russian mode @ [ \ ] ^ give letters
            isru = bool(l2) and l2 in RU
            sh = code(l2) if l2 and not isru else code(l1)
            if isru:
                vals = [code(l1), code(l1), code(l2.lower()), code(l2)]
            else:
                vals = [code(l1), sh, code(l1), sh]
        for t in range(4):
            tabs[t][k] = vals[t]
names = ["KEYTAB_LAT", "KEYTAB_LAT_SH", "KEYTAB_RUS", "KEYTAB_RUS_SH"]
out = ["; generated by mkkeys.py"]
for n, t in zip(names, tabs):
    out.append(f"{n}:")
    for i in range(0, 72, 12):
        out.append("        DB " + ", ".join(f"0{v:02X}h" for v in t[i:i + 12]))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
